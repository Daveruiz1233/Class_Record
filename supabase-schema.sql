-- Run this script in Supabase SQL Editor before using the GitHub Pages frontend.
-- Authentication is handled by Supabase Auth (email/password).

create table if not exists public.students (
  id bigint generated by default as identity primary key,
  student_number text not null unique,
  last_name text not null,
  first_name text not null,
  middle_name text not null default '',
  course text not null default '',
  year_section text not null default '',
  email text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(id) on delete cascade,
  term text not null check (term in ('midterm', 'final')),
  category text not null check (category in ('recitation', 'activity', 'quiz', 'exam')),
  title text not null,
  score numeric not null check (score >= 0),
  max_score numeric not null check (max_score > 0),
  created_at timestamptz not null default now(),
  constraint score_not_over_max check (score <= max_score)
);

create index if not exists scores_student_term_idx
  on public.scores (student_id, term);

alter table public.students enable row level security;
alter table public.scores enable row level security;

drop policy if exists "Authenticated users can read students" on public.students;
create policy "Authenticated users can read students"
  on public.students for select to authenticated using (true);

drop policy if exists "Authenticated users can add students" on public.students;
create policy "Authenticated users can add students"
  on public.students for insert to authenticated with check (true);

drop policy if exists "Authenticated users can edit students" on public.students;
create policy "Authenticated users can edit students"
  on public.students for update to authenticated using (true) with check (true);

drop policy if exists "Authenticated users can delete students" on public.students;
create policy "Authenticated users can delete students"
  on public.students for delete to authenticated using (true);

drop policy if exists "Authenticated users can read scores" on public.scores;
create policy "Authenticated users can read scores"
  on public.scores for select to authenticated using (true);

drop policy if exists "Authenticated users can add scores" on public.scores;
create policy "Authenticated users can add scores"
  on public.scores for insert to authenticated with check (true);

drop policy if exists "Authenticated users can edit scores" on public.scores;
create policy "Authenticated users can edit scores"
  on public.scores for update to authenticated using (true) with check (true);

drop policy if exists "Authenticated users can delete scores" on public.scores;
create policy "Authenticated users can delete scores"
  on public.scores for delete to authenticated using (true);
